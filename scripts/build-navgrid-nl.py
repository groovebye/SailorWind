#!/usr/bin/env python3
"""
Build the IJsselmeer + Markermeer navigable-water grid (src/lib/navgrid-nl.data.ts).

Source: Rijkswaterstaat "Algemeen Dieptebestand IJsselmeergebied 2022" (CC0),
WCS bodemhoogte_ijsselmeergebied, 20 m raster, bed level in metres vs NAP,
EPSG:28992. EMODnet has no data behind the dikes, hence a separate grid.

A cell is navigable when at least MIN_FRACTION of its area has water at least
SAFE_DEPTH deep at the (winter) lake level LAKE_LEVEL_NAP.

The Houtribdijk (Enkhuizen-Lelystad) is only a few raster pixels wide, so after
averaging it would leak. Inside DIKE_ZONE land is dilated and any cell that
touches it is blocked; the two lock complexes are then reopened along their
real fairways (GATES, from OpenStreetMap) so the lakes connect only there.

Usage: python build-navgrid-nl.py <ijg2022.tif>
"""
import base64, json, sys
import numpy as np
import rasterio
from pyproj import Transformer
from rasterio.warp import reproject, Resampling
from rasterio.transform import from_origin
from scipy import ndimage

LAT_MIN, LAT_MAX = 52.24, 53.10
LON_MIN, LON_MAX = 4.95, 6.03
RES = 0.0008                 # deg; ~89 m N-S, ~54 m E-W
LAKE_LEVEL_NAP = -0.40       # m; winter target level IJsselmeer / Markermeer
SAFE_DEPTH = 2.2             # m of water needed
MIN_FRACTION = 0.35          # share of a cell that must be deep enough
MIN_COMPONENT_CELLS = 2000   # drop isolated water smaller than this (~10 km²)
DIKE_ZONE = (52.500, 5.265, 52.715, 5.500)   # lat0, lon0, lat1, lon1 around the Houtribdijk
DIKE_DILATE_PX = 2                            # 20 m pixels added on each side of the dike
# Lock complexes reopened as navigable corridors: (name, [(lat, lon), ...]).
GATES = [
    ("Naviduct Krabbersgat (Enkhuizen)", [
        (52.6750, 5.2620), (52.682848, 5.27244), (52.682743, 5.274583), (52.683512, 5.277132),
        (52.684948, 5.279571), (52.685577, 5.281279), (52.685806, 5.288149), (52.686216, 5.290307),
        (52.687858, 5.293759), (52.689211, 5.295062), (52.691445, 5.295759), (52.693777, 5.296234),
        (52.69555, 5.296283), (52.69807, 5.295863), (52.700079, 5.2968), (52.7050, 5.2985)]),
    ("Houtribsluizen (Lelystad)", [(52.5215, 5.4343), (52.5265, 5.4344), (52.5287, 5.4345), (52.5335, 5.4347)]),
]

COLS = round((LON_MAX - LON_MIN) / RES)
ROWS = round((LAT_MAX - LAT_MIN) / RES)

with rasterio.open(sys.argv[1]) as src:
    bed = src.read(1).astype("float64")
    valid = bed < 1e300
    deep = np.where(valid & (bed <= LAKE_LEVEL_NAP - SAFE_DEPTH), 1.0, 0.0)
    dst = dict(dst_transform=from_origin(LON_MIN, LAT_MAX, RES, RES), dst_crs="EPSG:4326",
               src_transform=src.transform, src_crs=src.crs)
    frac = np.zeros((ROWS, COLS), dtype="float64")
    reproject(deep, frac, resampling=Resampling.average, **dst)

    # Dike mask: dry land (no data or above lake level) inside DIKE_ZONE, dilated.
    to_rd = Transformer.from_crs("EPSG:4326", "EPSG:28992", always_xy=True)
    xs, ys = to_rd.transform([DIKE_ZONE[1], DIKE_ZONE[3]], [DIKE_ZONE[0], DIKE_ZONE[2]])
    (r0, c0), (r1, c1) = src.index(min(xs), max(ys)), src.index(max(xs), min(ys))
    zone = np.zeros(bed.shape, bool)
    zone[max(r0, 0):r1 + 1, max(c0, 0):c1 + 1] = True
    land = zone & (~valid | (bed > LAKE_LEVEL_NAP))
    dike = ndimage.binary_dilation(land, iterations=DIKE_DILATE_PX) & zone
    dike_hit = np.zeros((ROWS, COLS), dtype="float64")
    reproject(dike.astype("float64"), dike_hit, resampling=Resampling.max, **dst)

nav = (frac >= MIN_FRACTION) & ~(dike_hit > 0)

def cell(lat, lon):
    return int((LAT_MAX - lat) / RES), int((lon - LON_MIN) / RES)

import os
for _name, pts in ([] if os.environ.get("NO_GATES") else GATES):
    for (la0, lo0), (la1, lo1) in zip(pts, pts[1:]):
        n = int(max(abs(la1 - la0), abs(lo1 - lo0)) / (RES / 3)) + 1
        for t in np.linspace(0, 1, n + 1):
            r, c = cell(la0 + (la1 - la0) * t, lo0 + (lo1 - lo0) * t)
            nav[max(r - 1, 0):r + 2, max(c - 1, 0):c + 2] = True

# Keep only large connected water (4-connected, as the router moves). Small deep
# pockets — harbour basins behind shallow or sub-cell entrances — would trap a
# route's snapped start/end; without them endpoints snap to the open lake.
lab, _ = ndimage.label(nav)
sizes = np.bincount(lab.ravel()); sizes[0] = 0
nav = np.isin(lab, np.flatnonzero(sizes >= MIN_COMPONENT_CELLS))

bits = np.packbits(nav.astype(np.uint8).ravel())
b64 = base64.b64encode(bits.tobytes()).decode()
meta = {"latMax": LAT_MAX, "lonMin": LON_MIN, "res": RES, "rows": ROWS, "cols": COLS,
        "safeDepthM": SAFE_DEPTH, "lakeLevelNap": LAKE_LEVEL_NAP}
out = os.environ.get("OUT", "src/lib/navgrid-nl.data.ts")
with open(out, "w") as f:
    f.write("// Generated by scripts/build-navgrid-nl.py from Rijkswaterstaat bathymetry\n")
    f.write("// (Algemeen Dieptebestand IJsselmeergebied 2022, CC0). Do not edit by hand.\n")
    f.write(f"export const NAVGRID_NL_META = {json.dumps(meta)} as const;\n")
    f.write(f'export const NAVGRID_NL_B64 = "{b64}";\n')
print(f"grid {ROWS}x{COLS}, navigable {nav.mean()*100:.1f}%, b64 {len(b64)/1024:.0f} KB -> {out}")
np.save("/tmp/sw-nav-nl.npy", nav)
